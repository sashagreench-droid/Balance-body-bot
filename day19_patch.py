import runpy
import content
import bot

# Day 19: build a balanced meal quickly from the foods already available at home.
content.DAY_TASKS[19] = (
    "Сегодня учимся собирать полноценный прием пищи даже тогда, когда дома осталось всего несколько продуктов.",
    "Представь, что до следующей закупки осталось несколько продуктов из того, что уже есть дома. Выбери из них те, из которых можно быстро собрать сбалансированный прием пищи за 5–10 минут. Прикинь, где здесь белок, источник углеводов, овощи/фрукты и жиры. Собери блюдо и, если хочешь, отправь фото.",
    "Что ты собрала из продуктов, которые были дома?\nУдалось ли сделать прием пищи сбалансированным? Чего, возможно, не хватило?\nЧто ты теперь будешь учитывать, когда дома остается немного продуктов?"
)


_original_reflection_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 19:
        answer = text.strip()
        return (
            "Спасибо за ответ ❤️\n\n"
            f"Ты собрала прием пищи из того, что уже было дома: «{answer}». И это как раз тот навык, который мы сегодня тренируем — не зависеть от идеального набора продуктов, а уметь адаптировать рацион к реальной ситуации.\n\n"
            "Если в твоем варианте был источник белка, углеводов и овощи/фрукты, а при необходимости немного жиров — прием пищи получился достаточно сбалансированным. "
            "Если какого-то компонента не хватило, это не ошибка: теперь ты знаешь, что можно добавить или предусмотреть при следующей закупке.\n\n"
            "Главное — ты увидела, что сбалансированный рацион можно собрать даже из ограниченного количества продуктов."
        )
    return _original_reflection_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback

# Keep all existing patches and production startup logic.
runpy.run_module("day18_patch", run_name="__main__")
