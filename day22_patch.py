# Day 22 gets feedback tied directly to the three restaurant situations.
_original_reflection_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 22:
        return (
            "🌿 Разбираем твои выборы\n\n"
            "Сегодня ты потренировалась смотреть на ресторанное меню не как на список «можно/нельзя», а как на набор вариантов, из которых можно собрать подходящий прием пищи.\n\n"
            "На завтрак, обед и ужин выбор действительно может отличаться — и это нормально. Важно учитывать, что уже было в рационе, чего хочется и что поможет собрать полноценный прием пищи.\n\n"
            "Твоя задача — не искать идеальное блюдо в ресторане, а научиться спокойно выбирать из того, что есть в меню, и адаптировать выбор под свой рацион."
        )
    return _original_reflection_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback

