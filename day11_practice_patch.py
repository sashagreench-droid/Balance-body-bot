_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 11:
        t = (text or "").strip().lower()
        parts = []

        if any(x in t for x in ("сложно", "трудно", "неудоб", "забыва", "запомнить")):
            parts.append("Ты заметила, что именно внесение некоторых продуктов пока требует внимания. Это нормально: сейчас ты осваиваешь инструмент. Наша цель — постепенно сделать его привычным, а не проводить весь день в приложении.")
        if any(x in t for x in ("легко", "просто", "удобно", "проще")):
            parts.append("Если внесение оказалось достаточно простым, значит сам инструмент уже начинает становиться понятнее. Теперь важно сохранить главное — счётчик помогает принимать решения, но не должен решать за тебя.")
        if any(x in t for x in ("идеал", "идеальн", "цифр", "попасть", "лимит", "урез", "меньше", "бо́льше", "больше", "страш")):
            parts.append("Ты заметила влияние самой цифры на выбор еды. Это важный момент: задача не в том, чтобы любой ценой попасть в число, а в том, чтобы использовать его как ориентир и не компенсировать еду ограничениями.")
        if any(x in t for x in ("ориентир", "информац", "спокой", "инструмент", "помог")):
            parts.append("Это именно то отношение, к которому мы идём: цифра даёт информацию о рационе, но не ставит ему оценку и не делает продукт «хорошим» или «плохим».")
        if any(x in t for x in ("не меня", "оставила", "ничего не меня", "не уреза", "не пропуска")):
            parts.append("Очень хороший навык — не начинать компенсировать питание из-за одной цифры. Так счётчик остаётся инструментом, а не превращается в систему наказаний.")

        if not parts:
            parts.append("Ты потренировалась вносить обычный день без попытки сделать его идеальным. Сейчас важно не количество цифр, а то, насколько спокойно ты можешь на них смотреть и принимать решения без запретов и компенсаций.")

        return "День 11 пройден ❤️\n\n" + "\n\n".join(parts) + "\n\nСмысл счётчика — дать тебе информацию, а не заставить подчиняться цифре."

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
