import bot
import content
import db

# Day 39 — make the task concrete and add a day-specific reflection.
item = content.DAY_TASKS.get(39)
if item:
    task, practice, reflection = item
    practice = (
        "📝 ПРАКТИКА\n\n"
        "Сегодня не нужно просто сравнивать себя с прошлым.\n"
        "Наша задача — увидеть, что конкретно изменилось в тебе за время курса.\n\n"
        "Выбери 3 сферы, которые тебе подходят:\n"
        "🏃‍♀️ движение и тренировки\n"
        "🍽 питание и выбор еды\n"
        "🧠 отношение к еде и подсчетам\n"
        "💪 самочувствие и энергия\n"
        "😴 сон и восстановление\n"
        "❤️ отношение к себе\n"
        "📅 регулярность и привычки\n\n"
        "Для каждой выбранной сферы напиши:\n"
        "➡️ Раньше у меня было…\n"
        "➡️ Сейчас у меня…\n"
        "➡️ Что помогло мне измениться…\n\n"
        "🌿 Например:\n"
        "«Раньше я пропускала тренировки, если не было настроения.\n"
        "Сейчас стараюсь сделать хотя бы короткую тренировку.\n"
        "Мне помогло перестать воспринимать тренировку как наказание и увидеть в ней пользу для самочувствия».\n\n"
        "🎯 Важно: не оценивай себя по весу или внешности.\n"
        "Сегодня мы тренируем навык замечать собственный прогресс — даже если он состоит из маленьких изменений.\n\n"
        "Когда закончишь — нажми «Я ВЫПОЛНИЛА» и ответь на вопросы рефлексии."
    )
    content.DAY_TASKS[39] = (task, practice, reflection)


_original_start_reflection = bot.start_reflection
_original_reflection_feedback = bot.reflection_feedback


async def start_reflection(q, context):
    uid = q.from_user.id
    u = db.user(uid)
    n = u["current_day"] if u else None

    if n == 39:
        context.user_data["awaiting_reflection"] = True
        await q.message.reply_text(
            "🌿 <b>Теперь рефлексия</b>\n\n"
            "1️⃣ В какой из выбранных сфер ты заметила самый большой прогресс?\n\n"
            "2️⃣ Что из того, чему ты научилась за курс, тебе особенно важно сохранить после его окончания?\n\n"
            "Напиши ответ одним сообщением. Я дам тебе обратную связь именно по твоему ответу, а потом мы завершим день.",
            parse_mode="HTML",
        )
        return

    await _original_start_reflection(q, context)


def reflection_feedback(day, text, uid=None):
    if day != 39:
        return _original_reflection_feedback(day, text, uid)

    t = text.lower()
    if any(x in t for x in ("пит", "еда", "рацион", "калор", "бжу", "белок")):
        return (
            "❤️ Ты заметила прогресс именно в питании — и это особенно важно, потому что твоя задача сейчас не просто знать правила, "
            "а уметь самостоятельно применять их в обычной жизни. Сохрани то решение или привычку, которую назвала: именно она поможет не вернуться к старому сценарию."
        )
    if any(x in t for x in ("трен", "движ", "шаг", "спорт", "заряд")):
        return (
            "❤️ Ты заметила изменения в движении и тренировках. Это хороший показатель того, что активность постепенно становится частью твоей жизни, "
            "а не только способом повлиять на вес. Особенно ценно, что ты уже видишь конкретную разницу между «раньше» и «сейчас»."
        )
    if any(x in t for x in ("самочув", "энерг", "сон", "устал")):
        return (
            "❤️ Ты заметила изменения в самочувствии — это один из самых важных результатов, который легко не замечать, если смотреть только на вес. "
            "Обрати внимание на эту связь и сохрани те привычки, которые помогли тебе почувствовать себя лучше."
        )
    if any(x in t for x in ("себ", "увер", "спокой", "отнош", "люб", "перестала боят", "не боюсь")):
        return (
            "❤️ Ты заметила изменения в отношении к себе. Это особенно ценно: устойчивые привычки строятся не на постоянной критике, "
            "а на способности спокойно принимать решения и замечать свой прогресс. Сохрани это отношение и после курса."
        )
    return (
        "❤️ Ты уже можешь сравнить не себя с другими, а себя сегодняшнюю с собой прошлой — именно этому и был посвящён сегодняшний день. "
        "Самое важное сейчас — сохранить тот навык или решение, которое ты назвала своим главным результатом. Это и есть твоя опора после курса."
    )


bot.start_reflection = start_reflection
bot.reflection_feedback = reflection_feedback
