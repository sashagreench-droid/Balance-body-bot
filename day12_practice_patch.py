import bot

# BALANCE BODY — День 12: turn "find 5 protein sources" into a concrete
# exercise that teaches what counts as a useful protein base in real meals.

bot.DAY_TASKS[12] = (
    "Сегодня разбираемся, где в твоём обычном питании брать белок и как сделать его регулярной частью рациона.",
    """🧠 Сначала небольшая теория

Белок нужен не только тем, кто занимается спортом. Он участвует в поддержании и восстановлении тканей, а ещё помогает сделать приём пищи более сытным.

Белок есть в разных продуктах: мясо, птица, рыба, яйца, творог и другие молочные продукты, бобовые, тофу и другие продукты.

Тебе не нужно превращать каждый приём пищи в «белковый» и не нужно есть только курицу с творогом. Задача — понять, какие источники белка тебе реально нравятся и удобно использовать.

Важно и другое: продукт может содержать белок, но его количество может сильно отличаться. Поэтому сегодня мы не просто составляем длинный список продуктов, а учимся находить белковую основу для обычных блюд.

📝 ПРАКТИКА

Шаг 1. Составь список минимум из 5 источников белка, которые ты реально готова есть.

Шаг 2. Напротив каждого напиши:
• в каком блюде ты обычно его ешь;
• насколько тебе удобно его готовить — легко / нормально / сложно;
• нравится ли тебе его вкус.

Шаг 3. Посмотри на свой обычный день и выбери 3 приёма пищи.
Для каждого напиши:
• что ты обычно ешь;
• где в этом приёме пищи находится белковая часть;
• если её мало или её нет — что можно добавить без полной переделки блюда.

Например:
🍳 Завтрак — яйца + тосты. Белковая основа уже есть.
🥗 Обед — салат + хлеб. Можно добавить курицу, рыбу, яйца или бобовые.
🍝 Ужин — паста. Можно добавить мясо/птицу, морепродукты, сыр или другой подходящий источник белка.

Шаг 4. Выбери 2 быстрых варианта, которые сможешь использовать в день, когда нет времени готовить.

Шаг 5. Ответь:
👉 Какой источник белка мне проще всего добавить в рацион?
👉 В каком приёме пищи мне чаще всего не хватает белковой основы?
👉 Что я могу изменить уже завтра без сложного меню и готовки?

Главная задача дня — не начать есть «идеально», а собрать свою личную базу белковых продуктов, которыми тебе удобно пользоваться.""",
    """После задания напиши одним сообщением:

1️⃣ Мои 5 источников белка — …
2️⃣ Чаще всего белка мне не хватает в — …
3️⃣ Завтра я добавлю — …
4️⃣ Самый удобный для меня источник — …

По твоему ответу я помогу понять, где именно в твоём рационе проще всего сделать белок регулярным."""
)

_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 12:
        t = (text or "").strip().lower()
        parts = []

        if any(x in t for x in ("куриц", "индей", "мяс", "говядин", "свинин")):
            parts.append("Ты выбрала мясо или птицу как удобную белковую основу. Хорошо, что мы ищем не абстрактно «правильный продукт», а то, что реально вписывается в твою обычную еду.")
        if any(x in t for x in ("рыб", "лосос", "тунец", "морепродукт")):
            parts.append("Рыба и морепродукты могут стать хорошей белковой опорой для обычных блюд. Главное сейчас — найти варианты, которые тебе действительно удобно есть регулярно.")
        if any(x in t for x in ("яйц", "омлет")):
            parts.append("Яйца — удобный вариант для завтрака и быстрых блюд. Ты уже можешь использовать их как одну из своих простых белковых опор.")
        if any(x in t for x in ("творог", "йогурт", "сыр", "молоч")):
            parts.append("Молочные продукты дают тебе ещё один простой способ добавить белковую основу без отдельной сложной готовки. Выбирай те варианты, которые тебе нравятся и подходят твоему рациону.")
        if any(x in t for x in ("фасол", "чечевиц", "нут", "бобов", "тофу")):
            parts.append("Бобовые или тофу — хороший способ разнообразить источники белка и не строить рацион только вокруг мяса и молочных продуктов.")
        if any(x in t for x in ("завтрак", "утром")):
            parts.append("Если именно на завтраке белковая часть пока слабее, это удобная точка для первого изменения: не перестраивать весь рацион, а добавить один привычный источник белка.")
        if any(x in t for x in ("обед", "днём", "днем")):
            parts.append("Если белка не хватает в обед, проще всего не придумывать новое меню, а добавить источник белка к тому, что ты уже ешь.")
        if any(x in t for x in ("ужин", "вечер")):
            parts.append("Если именно вечером белковая часть получается случайной, попробуй заранее иметь один простой вариант, который можно добавить к обычному ужину.")
        if any(x in t for x in ("быстр", "нет времени", "времени нет", "удобн", "легко")):
            parts.append("Ты сразу ищешь быстрый вариант — это правильный фокус для самостоятельности. Работает не самый «идеальный» источник белка, а тот, который ты действительно будешь использовать.")

        if not parts:
            parts.append("Ты начала собирать свою личную базу белковых продуктов. Теперь важно смотреть не на идеальное меню, а на то, какой источник тебе реально удобно добавлять в обычные блюда.")

        return "День 12 пройден ❤️\n\n" + "\n\n".join(parts) + "\n\nТвоя задача — не есть одинаковый набор продуктов каждый день, а научиться самостоятельно находить белковую основу в своём обычном рационе."

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
