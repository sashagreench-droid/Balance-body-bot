def reflection_feedback(day, text, uid=None):
    if day == 9:
        t = (text or "").strip().lower()
        parts = []

        if any(x in t for x in ("страш", "боюсь", "боялась", "запрет", "нельзя", "запрещ")):
            parts.append("Ты заметила связь между калорийностью и ощущением «нельзя». Именно её мы сейчас и меняем: цифра на упаковке не запрещает продукт — она просто помогает понимать его энергетическую ценность.")
        if any(x in t for x in ("шоколад", "сладк", "десерт", "сыр", "орех", "масло")):
            parts.append("Ты выбрала продукт, который часто кажется «слишком калорийным». Здесь важно смотреть не только на число калорий, но и на реальную порцию: более калорийный продукт можно встроить в рацион, если учитывать его количество.")
        if any(x in t for x in ("порци", "грамм", "100 г", "100г", "колич")):
            parts.append("Хорошо, что ты посмотрела на размер порции. Калорийность на 100 г и калорийность того количества, которое ты реально съедаешь, — не одно и то же. Именно поэтому сравнивать продукты лучше вместе с порцией.")
        if any(x in t for x in ("удив", "не ожид", "оказыва", "поняла", "понял", "заметила", "заметил")):
            parts.append("Главное открытие здесь — цифры могут отличаться от твоего ощущения о продукте. Чем спокойнее ты умеешь смотреть на эти цифры, тем меньше решений принимается из страха и тем больше — осознанно.")
        if any(x in t for x in ("спокой", "информац", "встро", "можно есть", "можно впис")):
            parts.append("Ты уже начинаешь воспринимать калории как инструмент, а не как список запретов. Именно это нам нужно: знать цифры, но не бояться еды из-за них.")

        if not parts:
            parts.append("Ты потренировалась смотреть на калорийность без автоматической оценки «хорошо/плохо». Теперь важно продолжать замечать не только цифру, но и реальную порцию и место продукта в твоём рационе.")

        return "День 9 пройден ❤️\n\n" + "\n\n".join(parts) + "\n\nДальше мы перейдём от общего понимания калорий к твоему личному ориентиру и тому, как использовать его без постоянного контроля."

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
