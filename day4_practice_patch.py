_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 4:
        t = (text or "").strip().lower()
        lines = []

        if any(p in t for p in ("кофе", "соус", "кусоч", "конфет", "перекус", "сладк", "не счит", "не замеч")):
            lines.append("Ты заметила то, что раньше легко выпадало из общей картины питания. Именно для этого мы сейчас и фиксируем рацион: не чтобы запретить эти продукты, а чтобы видеть их без фильтров.")

        if any(p in t for p in ("скры", "стыд", "показать", "правильн", "изменить", "идеальн", "тренер", "бот")):
            lines.append("Ты заметила желание сделать свой рацион «правильнее» для чужих глаз. Это важный момент: нам не нужно соответствовать картинке. Чем честнее наблюдение, тем полезнее выводы о себе.")

        if any(p in t for p in ("автомат", "по привыч", "привычк", "не была голод", "не голод", "за компанию", "эмоци", "стресс", "устал")):
            lines.append("Ты увидела момент, когда еда могла происходить не только из физического голода. Не нужно сейчас это запрещать — важно научиться замечать, что именно запускает такой сценарий.")

        if any(p in t for p in ("понял", "поняла", "узнал", "заметил", "заметила", "раньше", "впервые")):
            lines.append("Это и есть результат сегодняшнего дня: у тебя появляется собственная информация о питании, а не оценка «хорошо/плохо».")

        if lines:
            return "Спасибо за честный разбор ❤️\n\n" + "\n\n".join(lines) + "\n\nСегодня ничего не нужно компенсировать или исправлять. Забираем наблюдение и двигаемся дальше."

        return (
            "Спасибо за честный ответ ❤️\n\n"
            "Смысл Дня 4 — не собрать идеальный рацион, а увидеть настоящий: вместе с кофе, сладким, перекусами и небольшими добавками. "
            "Когда ты видишь всю картину без фильтров, дальше гораздо легче самостоятельно принимать решения."
        )

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
