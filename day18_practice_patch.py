_original_feedback = bot.reflection_feedback

def reflection_feedback(day, text, uid=None):
    if day == 18:
        t = (text or "").strip().lower()
        parts = []
        if any(x in t for x in ("сыр", "орех", "масло", "авокад", "соус", "майон", "сливк", "шоколад")):
            parts.append("Ты выбрала продукты, где жиры действительно могут заметно повышать калорийность порции. Здесь важнее не запрет, а удобный размер порции.")
        if any(x in t for x in ("уменьш", "меньше", "порци")):
            parts.append("Хорошее решение — сначала работать с порцией, а не убирать любимый продукт полностью.")
        if any(x in t for x in ("замен", "альтернатив")):
            parts.append("Если замена сохраняет вкус и тебе реально удобна, это рабочий инструмент. Но заменять продукт только потому, что он жирный, не обязательно.")
        if any(x in t for x in ("остав", "как есть", "оставлю")):
            parts.append("Если продукт спокойно вписывается в рацион в привычной порции, его не нужно менять ради самого факта наличия жиров.")
        if not parts:
            parts.append("Смысл Дня 18 — научиться видеть, где жиры влияют на калорийность, и выбирать удобное действие без крайностей.")
        return "День 18 пройден ❤️\n\n" + "\n\n".join(parts)
    return _original_feedback(day, text, uid)

bot.reflection_feedback = reflection_feedback
