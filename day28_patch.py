_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 28:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    items = sum(1 for marker in ("1.", "2.", "3.", "1️⃣", "2️⃣", "3️⃣") if marker in t)
    food_words = (
        "йогурт", "творог", "яйц", "омлет", "сыр", "суп", "смузи", "банан", "ягод", "фрукт",
        "хлеб", "тост", "каша", "овсян", "рис", "картоф", "авокадо", "орех", "кефир", "молок",
        "куриц", "рыб", "тунц", "лосос", "протеин", "бутерброд", "сэндвич"
    )
    has_food = any(w in t for w in food_words)
    has_reason = any(w in t for w in ("легче", "аппетит", "не хочу есть", "не хочется", "плохо ем", "утром", "вечером", "после"))

    if items >= 3 and has_food:
        return (
            f"🌿 Отлично. Ты собрала конкретные варианты на случай плохого аппетита:\n\n{answer}\n\n"
            "И вот здесь появляется важный навык: тебе не нужно ждать, пока аппетит станет идеальным. Ты умеешь менять размер и формат приема пищи так, чтобы еда оставалась посильной.\n\n"
            "Это важно, потому что при сниженном аппетите легко начать пропускать еду, а позже столкнуться с сильным голодом и хаотичным питанием. Гораздо полезнее иметь несколько небольших вариантов, которые ты реально можешь съесть.\n\n"
            "Теперь выбери один из трех как свой самый простой вариант «когда совсем не хочется есть». ❤️"
        )

    if has_food or has_reason:
        return (
            f"🌿 Хорошее начало. Ты уже обозначила: «{answer}».\n\n"
            "Сегодня нам важно не просто назвать еду, а собрать 3 конкретных небольших приема пищи на случай плохого аппетита. Подумай о том, что тебе легче есть небольшим объемом.\n\n"
            "Дополни ответ еще вариантами и для каждого проверь: есть ли источник белка, чем можно добавить углеводы и насколько легко это съесть.\n\n"
            "Почему это важно: цель не в том, чтобы заставлять себя есть большую порцию. Мы учимся адаптировать формат и объем еды под состояние, не выпадая из питания. ❤️"
        )

    if "сложно" in t or "не знаю" in t:
        return (
            "🌿 Давай упростим. Вспомни продукты, которые ты можешь съесть даже при небольшом аппетите.\n\n"
            "Например: йогурт + банан; творог + ягоды; омлет + тост; суп-пюре + хлеб; смузи на основе йогурта или молока.\n\n"
            "Это только примеры. Выбери 3 варианта, которые подходят именно тебе, и напиши их одним сообщением.\n\n"
            "Смысл задания — заранее иметь несколько маленьких и удобных решений, чтобы при плохом аппетите не пропускать еду автоматически. ❤️"
        )

    return (
        f"🌿 Давай сделаем ответ конкретнее. Ты написала: «{answer}».\n\n"
        "Сегодня нужно составить 3 небольших приема пищи, которые тебе легче съесть при плохом аппетите. Не просто «что-нибудь легкое», а конкретно: например, «йогурт + банан» или «омлет + тост».\n\n"
        "После этого выбери один самый простой вариант.\n\n"
        "И помни, зачем мы это делаем: не заставлять себя есть большую порцию, а научиться адаптировать объем и формат еды под состояние, сохраняя питание. ❤️"
    )


bot.reflection_feedback = reflection_feedback
