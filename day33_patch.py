_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 33:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    answered = sum(1 for marker in ("1.", "2.", "3.", "4.") if marker in t)
    adaptation = any(w in t for w in ("адаптир", "продолж", "ориентир", "выбира", "подстро", "систем"))
    dessert = any(w in t for w in ("десерт", "сладк", "торт", "морожен", "чизкейк"))
    difficulty = any(w in t for w in ("сложно", "трудно", "сложнее", "сомнева", "не знаю"))

    if answered >= 4 and adaptation and dessert:
        return (
            "🎯 Отлично. Ты показала не просто знание правил, а способность принимать решения, когда привычный план меняется.\n\n"
            f"Твой ответ:\n{answer}\n\n"
            "Самое важное здесь — ты не ищешь идеальных условий. Ты выбираешь достаточно хороший вариант, учитываешь ситуацию и продолжаешь дальше. Именно это и есть адаптация. ❤️"
        )

    if difficulty:
        return (
            "🌿 Хорошо, что ты заметила, какая часть ситуации вызывает сложности. Это как раз та точка, которую важно превратить в конкретный навык.\n\n"
            f"Ты написала:\n{answer}\n\n"
            "В следующий раз попробуй заранее определить одно простое действие, которое поможет тебе в такой ситуации: как выбрать блюдо, как поступить с десертом или как продолжить питание после изменения планов. ❤️"
        )

    return (
        "🌿 Хорошая работа. Контрольная нужна не для того, чтобы найти «идеальный» вариант, а чтобы увидеть, как ты принимаешь решения в реальной жизни.\n\n"
        f"Ты написала:\n{answer}\n\n"
        "Если в похожей ситуации планы снова изменятся, твоя задача — не начинать всё заново, а спокойно адаптировать следующий приём пищи и продолжить систему. ❤️"
    )


bot.reflection_feedback = reflection_feedback
