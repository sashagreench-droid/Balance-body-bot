_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 33:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    answered = sum(1 for marker in ("1.", "2.", "3.", "4.") if marker in t)
    adaptation = any(w in t for w in ("адаптир", "продолж", "ориентир", "выбира", "подстро", "систем"))
    no_compensation = any(w in t for w in ("не буду", "не стану", "не компенс", "не пропущ", "не голод", "не трениров"))
    dessert = any(w in t for w in ("десерт", "сладк", "торт", "морожен", "чизкейк"))

    if answered >= 4 and adaptation and dessert:
        feedback = (
            "🎯 Отлично. Ты не просто ответила на вопросы — ты показала логику принятия решений в ситуации, где невозможно контролировать всё.\n\n"
            f"Твой ответ:\n{answer}\n\n"
            "Самый важный навык здесь — не найти идеальный вариант, а выбрать достаточно хороший вариант и спокойно продолжить дальше. Именно это и есть адаптация."
        )
        if no_compensation:
            feedback += "\n\n❤️ Особенно хорошо, что в твоём ответе нет идеи «отработать» или компенсировать десерт. Один прием пищи не требует наказания или исправления."
        feedback += "\n\nТеперь ответь на второй вопрос рефлексии: что ты сделаешь по-другому в похожей ситуации в реальной жизни?"
        return feedback

    if answered >= 2:
        return (
            "🌿 Ты уже начала разбирать ситуацию как человек, который умеет адаптироваться, а не как человек, которому нужен идеальный план.\n\n"
            f"Ты написала:\n{answer}\n\n"
            "Но контрольная проверяет именно последовательность решений. Поэтому допиши все 4 пункта:\n"
            "1️⃣ выбор в ресторане;\n"
            "2️⃣ решение про десерт;\n"
            "3️⃣ следующий прием пищи вне дома;\n"
            "4️⃣ главный принцип, который помогает продолжить без компенсации.\n\n"
            "❤️ Нам важно увидеть не «правильное питание», а твою способность спокойно продолжать систему, когда планы меняются."
        )

    return (
        "🧩 Давай разберем ситуацию пошагово. Здесь не нужно угадывать правильный ответ.\n\n"
        "Представь: ты в ресторане → выбираешь десерт → планы меняются → следующий прием пищи снова вне дома.\n\n"
        "Напиши:\n\n"
        "1️⃣ Что выберешь в ресторане?\n"
        "2️⃣ Что сделаешь с десертом, если действительно его захочется?\n"
        "3️⃣ Как выберешь следующий прием пищи вне дома?\n"
        "4️⃣ Что поможет тебе сохранить систему и не пытаться компенсировать съеденное?\n\n"
        "🌿 Отвечай конкретно — можно по 1–2 предложения на каждый пункт. ❤️"
    )


bot.reflection_feedback = reflection_feedback
