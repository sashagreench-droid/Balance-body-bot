_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 7:
        t = (text or "").strip().lower()
        parts = []

        if any(x in t for x in ("сладк", "конфет", "шоколад", "десерт")):
            parts.append("Ты уже видишь конкретный сценарий со сладким. Следующий шаг — не запрещать его, а замечать, что обычно происходит до желания съесть сладкое: голод, усталость, стресс или привычное время.")
        elif any(x in t for x in ("кофе", "чай", "напит")):
            parts.append("Ты заметила напитки как часть своего реального рациона. Это полезное наблюдение: такие небольшие эпизоды легко не замечать, хотя они тоже входят в общую картину дня.")

        if any(x in t for x in ("вечер", "ночью", "перед сном", "после работы")):
            parts.append("У тебя проявился вечерний сценарий. Не будем пока пытаться просто убрать вечернюю еду — важнее понять, что запускает её именно в это время и хватает ли тебе еды в течение дня.")

        if any(x in t for x in ("стресс", "устал", "скука", "скучно", "эмоци", "нерв")):
            parts.append("Ты связала еду с состоянием или эмоцией. Это важное наблюдение первой недели: теперь можно работать не только с продуктом, но и с тем, что происходит до еды.")

        if any(x in t for x in ("голод", "сытост", "насыщ")):
            parts.append("Ты уже смотришь не только на еду, но и на свои сигналы голода и сытости. Именно это помогает постепенно принимать решения не по запретам, а по реальной потребности.")

        if any(x in t for x in ("перекус", "кусоч", "между ед", "жую")):
            parts.append("Ты заметила эпизоды между основными приёмами пищи. Теперь важно не считать их ошибкой, а понимать: это был голод или конкретный привычный сценарий.")

        if any(x in t for x in ("раньше", "понял", "поняла", "заметил", "заметила", "теперь", "узнал", "узнала")):
            parts.append("Главный результат первой недели — у тебя появились собственные наблюдения вместо общей оценки «я правильно/неправильно питаюсь». На них уже можно опираться дальше.")

        if not parts:
            parts.append("Ты прошла первую неделю и начала собирать собственную картину питания. Сейчас важнее всего конкретика: какой сценарий повторяется, что происходит перед едой и что ты хочешь изменить первым.")

        return "Первая контрольная пройдена ❤️\n\n" + "\n\n".join(parts) + "\n\nНа следующей неделе мы начнём разбираться не только в том, что происходит, но и в том, почему разные продукты и порции по-разному влияют на твой рацион."

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
