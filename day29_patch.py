_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 29:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    meal_markers = ("завтрак", "обед", "ужин", "перекус")
    meals = sum(1 for marker in meal_markers if marker in t)
    food_words = (
        "яйц", "омлет", "творог", "йогурт", "сыр", "куриц", "индейк", "мяс", "рыб", "лосос", "тунц", "белок", "протеин",
        "рис", "греч", "овсян", "каша", "хлеб", "тост", "макарон", "картоф", "лаваш", "фрукт", "яблок", "банан", "ягод", "овощ", "салат", "авокадо", "орех"
    )
    has_food = any(w in t for w in food_words)
    has_doubt = any(w in t for w in ("сложно", "сомнева", "не знаю", "не уверена", "трудно", "не умею"))

    if meals >= 3 and has_food:
        return (
            "🌿 Ты не просто написала меню — ты потренировала именно тот навык, ради которого мы делаем этот день.\n\n"
            f"Твой пример дня:\n{answer}\n\n"
            "Здесь важно не то, насколько точно ты попала бы в калории. Важно, что ты смогла самостоятельно выбрать еду и собрать приемы пищи, опираясь на состав, привычные порции и свои ориентиры.\n\n"
            "Теперь посмотри на два своих ответа в конце. То место, где было больше всего сомнений, — не ошибка, а подсказка, какой навык стоит еще потренировать.\n\n"
            "И сегодня действительно не нужно возвращаться в приложение ради проверки. Оставь этот день именно тренировкой самостоятельности. ❤️"
        )

    if has_doubt:
        return (
            "🌿 То, что без цифр появилось сомнение, — нормально. Мы как раз и тренируем этот переход.\n\n"
            "Не пытайся угадать калорийность каждого продукта. Сначала собери конкретный завтрак, обед и ужин, а затем посмотри на них через простые ориентиры: белок, углеводы, овощи/фрукты, подходящий источник жиров и привычная порция.\n\n"
            "Напиши свой пример дня, даже если в одном месте не уверена. Сегодня важнее самостоятельное решение, чем идеальная точность. ❤️"
        )

    return (
        "🌿 Давай сделаем ответ конкретнее.\n\n"
        "Сегодня нужно показать, на что ты можешь опираться вместо приложения. Составь конкретно:\n\n"
        "🍳 Завтрак — блюдо/продукты\n"
        "🍲 Обед — блюдо/продукты\n"
        "🍽 Ужин — блюдо/продукты\n"
        "🍎 Перекус — если нужен\n\n"
        "После этого ответь на 2 вопроса:\n"
        "1️⃣ Какой прием пищи было проще всего собрать без подсчета?\n"
        "2️⃣ Где больше всего сомневалась?\n\n"
        "Граммы и калории сегодня считать не нужно. Нам важно увидеть, можешь ли ты уже принимать адекватные решения без постоянной проверки цифр. ❤️"
    )


bot.reflection_feedback = reflection_feedback
