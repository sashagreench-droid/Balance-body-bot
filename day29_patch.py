_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 29:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    meal_markers = ("завтрак", "обед", "ужин", "перекус")
    meals = sum(1 for marker in meal_markers if marker in t)
    food_words = (
        "яйц", "омлет", "творог", "йогурт", "сыр", "куриц", "индейк", "мяс", "рыб", "лосос", "тунц", "белок", "протеин",
        "рис", "греч", "овсян", "каша", "хлеб", "тост", "макарон", "картоф", "лаваш", "фрукт", "яблок", "банан", "ягод", "овощ", "салат", "авокадо", "орех"
    )
    has_food = any(w in t for w in food_words)
    has_doubt = any(w in t for w in ("сложно", "сомнева", "не знаю", "не уверена", "трудно", "не умею"))

    if meals >= 3 and has_food:
        return (
            "🌿 Вот это и есть сегодняшний навык — принимать решения без постоянной проверки цифр.\n\n"
            f"Ты собрала свой день так:\n{answer}\n\n"
            "Посмотри, что ты уже можешь делать самостоятельно: выбирать конкретную еду, собирать приемы пищи и ориентироваться на состав и привычные порции, а не только на цифру калорий.\n\n"
            "Обрати внимание и на свои сомнения: если где-то было сложнее, это не значит, что ты сделала неправильно. Именно такие места показывают, какой навык еще стоит потренировать.\n\n"
            "И главное — сегодня не нужно идти в приложение и проверять результат. Оставь этот день как тренировку доверия к своим знаниям. ❤️"
        )

    if has_doubt:
        return (
            "🌿 Это нормально — после периода подсчета сначала может быть непривычно принимать решения без цифр.\n\n"
            "Но сегодня нам как раз важно потренировать этот переход. Не пытайся угадать калорийность каждого продукта. Собери конкретный завтрак, обед и ужин и проверь их по простым ориентирам: белок, углеводы, овощи/фрукты, подходящий источник жиров и привычная порция.\n\n"
            "Напиши свой пример дня — даже если в одном месте сомневаешься. Нам сейчас важнее увидеть твое самостоятельное решение, чем идеальную точность. ❤️"
        )

    return (
        "🌿 Давай сделаем ответ конкретнее.\n\n"
        "Сегодня нужно не просто провести день «без подсчета», а показать, на что ты можешь опираться вместо приложения. Составь конкретно:\n\n"
        "🍳 Завтрак — блюдо/продукты\n"
        "🍲 Обед — блюдо/продукты\n"
        "🍽 Ужин — блюдо/продукты\n"
        "🍎 Перекус — если нужен\n\n"
        "После этого проверь каждый основной прием пищи по четырем ориентирам: белок, углеводы, овощи/фрукты и подходящий источник жиров. Граммы и калории сегодня считать не нужно.\n\n"
        "Смысл задания — увидеть, можешь ли ты уже использовать свои знания без постоянной проверки цифр. ❤️"
    )


bot.reflection_feedback = reflection_feedback
