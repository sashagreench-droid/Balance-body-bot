import bot

_original_reflection_feedback = bot.reflection_feedback


def _day44_feedback(text, uid=None):
    t = (text or "").strip().lower()

    compensation = any(p in t for p in (
        "урезать калори", "сократить калори", "меньше калори", "не есть",
        "голод", "голодать", "пропустить прием", "пропустить приём",
        "отработать", "отрабатывать", "дополнительн.*трен", "наказать"
    ))
    restart = any(p in t for p in (
        "завтра начну", "с понедельника", "начну сначала", "начать сначала",
        "всё испорчено", "все испорчено", "день испорчен", "заново"
    ))
    calm_return = any(p in t for p in (
        "обычн", "следующ", "продолж", "не компенс", "без компенсац",
        "следующий прием", "следующий приём", "режим"
    ))

    if compensation:
        return (
            "Спасибо, что написала именно это ❤️\n\n"
            "Ты очень точно заметила свой автоматический сценарий: после неидеального дня появляется желание **урезать калории на следующий день**. "
            "Именно этот момент сегодня важно было увидеть.\n\n"
            "Заметь разницу: «я хочу меньше есть завтра» может казаться способом быстро исправить ситуацию, но по сути это попытка компенсировать уже произошедшее. "
            "А наша задача — не наказывать себя за один день, а научиться возвращаться к обычному режиму.\n\n"
            "Поэтому твоя новая точка опоры может звучать так:\n"
            "➡️ **«Если сегодня я съела больше обычного, завтра я не компенсирую. Я просто возвращаюсь к своему привычному режиму со следующего приёма пищи».**\n\n"
            "Ты уже сделала важную часть работы — не просто вспомнила, что происходило, а увидела собственную реакцию после этого. Именно из таких наблюдений постепенно складывается самостоятельность."
        )

    if restart:
        return (
            "Спасибо за честный ответ ❤️\n\n"
            "Ты заметила знакомую ловушку: один неидеальный день легко превращается в мысль «теперь начну заново». "
            "Но сегодняшний навык как раз про другое — **не обнулять уже сделанное**.\n\n"
            "Тебе не нужно ждать завтра или понедельника. Неидеальный эпизод уже закончился, а следующее решение всё ещё остаётся твоим.\n\n"
            "Попробуй заменить старую связку:\n"
            "«неидеальный день → всё испорчено → начну заново»\n\n"
            "на новую:\n"
            "«неидеальный день → замечаю → не компенсирую → делаю следующее обычное действие».\n\n"
            "Это намного ближе к реальной самостоятельности: не никогда не ошибаться, а уметь спокойно возвращаться."
        )

    if calm_return:
        return (
            "Мне нравится это наблюдение ❤️\n\n"
            "Ты уже смещаешь фокус с вопроса «как исправить вчера?» на вопрос «что я делаю дальше?». "
            "Именно это мы сегодня тренировали.\n\n"
            "Обрати внимание: возвращение — это не отдельный идеальный план. Это обычный следующий шаг: привычный приём пищи, привычная активность и продолжение своего режима без наказания и компенсации.\n\n"
            "Сохрани для себя короткую формулу:\n"
            "**неидеальный день ≠ нужно начинать сначала.**\n"
            "**неидеальный день → следующее обычное действие.**\n\n"
            "Ты не обязана делать всё идеально, чтобы продолжать. Навык как раз в том, чтобы уметь продолжать после того, как что-то пошло не по плану."
        )

    return (
        "Спасибо за честный ответ ❤️\n\n"
        "Сегодня важно было не дать себе правильный ответ, а увидеть свой реальный сценарий после неидеального дня. "
        "Если ты заметила хотя бы одну мысль, эмоцию или привычное действие после такого дня — это уже полезный материал.\n\n"
        "Посмотри на свой ответ ещё раз и спроси себя: **что я обычно делаю дальше и помогает ли это мне вернуться в режим или только усиливает желание всё компенсировать?**\n\n"
        "Главный навык Дня 44 — не идеальность. Это способность спокойно продолжать после неидеального эпизода."
    )


def reflection_feedback(day, text, uid=None):
    if day == 44:
        return _day44_feedback(text, uid)
    return _original_reflection_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
