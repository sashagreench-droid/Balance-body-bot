_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 30:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    protein_words = (
        "яйц", "омлет", "куриц", "индейк", "рыб", "лосос", "тунц", "творог",
        "йогурт", "сыр", "морепродукт", "кревет", "мяс", "говядин", "свин", "бобов", "чечев", "фасол", "протеин"
    )
    found = [w for w in protein_words if w in t]
    has_list = any(str(i) in t for i in range(1, 6))
    has_easy = any(w in t for w in ("легко", "удобно", "быстро", "нет времени", "приготов", "купить", "готов"))

    if len(set(found)) >= 3 and has_list:
        return (
            "🥩 Отлично — у тебя уже начинает формироваться собственная белковая база.\n\n"
            f"Ты выбрала:\n{answer}\n\n"
            "Здесь особенно ценно, что ты ищешь не абстрактно «правильные» продукты, а те, которые тебе нравятся и которые реально можно использовать в обычной жизни.\n\n"
            "Теперь посмотри на свои варианты и выдели 2 самых удобных на случай, когда совсем нет времени готовить. Именно такие продукты становятся опорой в реальном рационе: не требуют сложного планирования и помогают не оставлять белок на последний прием пищи.\n\n"
            "❤️ Сохрани этот список — дальше ты сможешь возвращаться к нему, когда не знаешь, что добавить в рацион."
        )

    if has_easy:
        return (
            "🥩 Хорошо, что ты смотришь не только на пользу продукта, но и на то, насколько удобно его использовать.\n\n"
            f"Твой ответ: {answer}\n\n"
            "Именно практичность делает белковую базу рабочей. Продукт может быть отличным по составу, но если его сложно купить или приготовить, в обычной жизни ты вряд ли будешь выбирать его регулярно.\n\n"
            "Допиши еще несколько конкретных вариантов и выбери 2 самых быстрых. Например: тунец — добавить к салату или съесть с хлебцами; греческий йогурт — взять как быстрый перекус. ❤️"
        )

    return (
        "🥩 Давай соберем список конкретнее.\n\n"
        "Нам нужны минимум 5 продуктов, которые ты реально можешь использовать:\n\n"
        "🥚 яйца\n"
        "🍗 курица / индейка\n"
        "🐟 рыба / тунец\n"
        "🥣 творог / греческий йогурт\n"
        "🧀 сыр\n"
        "🦐 морепродукты\n"
        "🥩 мясо\n"
        "🫘 бобовые\n\n"
        "📋 Напиши свои 5 вариантов, а затем выбери 2 самых удобных на случай, когда нет времени готовить, и укажи, как именно ты их съешь или добавишь в прием пищи.\n\n"
        "Цель — не найти идеальный продукт, а собрать свою личную белковую базу для обычной жизни. ❤️"
    )


bot.reflection_feedback = reflection_feedback
