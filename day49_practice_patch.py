import bot
from telegram import InlineKeyboardButton, InlineKeyboardMarkup

_original_show_practice = bot.show_practice


async def show_practice_day49(q, context):
    uid = q.from_user.id
    n = bot.db.user(uid)["current_day"]

    if n != 49:
        return await _original_show_practice(q, context)

    text = (
        "📝 <b>ПРАКТИКА — ФИНАЛЬНЫЙ КВЕСТ</b>\n\n"
        "Представь реальный день:\n\n"
        "Ты проснулась утром и понимаешь, что сегодня очень много дел. "
        "На нормальный обед времени почти нет. Вечером после работы тебя зовут в ресторан. "
        "Днём ты устала и заметила, что хочется сладкого. Калории сегодня считать не хочешь.\n\n"
        "Твоя задача — самостоятельно решить, как ты проведёшь этот день, используя навыки курса.\n\n"
        "Ответь одним сообщением на 6 вопросов:\n\n"
        "1️⃣ <b>Завтрак:</b> что съешь утром, чтобы получить нормальный приём пищи?\n\n"
        "2️⃣ <b>Нет времени на обед:</b> что выберешь вместо пропуска еды? Назови конкретный вариант.\n\n"
        "3️⃣ <b>Сладкое:</b> что сделаешь, если днём захочется сладкого?\n\n"
        "4️⃣ <b>Ресторан:</b> что будешь учитывать при выборе блюда? Назови свой вариант ужина.\n\n"
        "5️⃣ <b>Завтра:</b> если вечером съешь больше, чем планировала, что сделаешь на следующий день?\n\n"
        "6️⃣ <b>Главное:</b> какой навык курса поможет тебе пройти этот день без постоянного контроля?\n\n"
        "Здесь нет идеального меню. Мне важно увидеть <b>логику твоих решений</b>: как ты адаптируешь питание под реальную жизнь, не бросая систему.\n\n"
        "Напиши все 6 ответов одним сообщением. После этого я разберу твои решения и дам персональную обратную связь."
    )
    buttons = [
        [InlineKeyboardButton("📷 ОТПРАВИТЬ ФОТО", callback_data="photo")],
        [InlineKeyboardButton("✅ Я ВЫПОЛНИЛА", callback_data="donepractice")],
        [InlineKeyboardButton("🤔 МНЕ СЛОЖНО", callback_data="trainer")],
    ]
    await q.message.reply_text(
        text,
        parse_mode="HTML",
        reply_markup=InlineKeyboardMarkup(buttons),
    )


bot.show_practice = show_practice_day49
