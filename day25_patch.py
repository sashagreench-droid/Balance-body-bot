import runpy
import content
import bot

# Day 25: plan part of the day's meals from home and part on the road,
# while keeping the plan aligned with the user's own calorie target.
content.DAY_TASKS[25] = (
    "Сегодня учимся заранее продумывать питание в поездке: часть еды берем из дома, а часть спокойно покупаем по дороге.",
    "Представь, что завтра тебе предстоит поездка на весь день. Составь план питания под свою калорийность.\n\nСделай по шагам:\n1️⃣ Выбери 1–2 приема пищи или перекуса, которые удобно взять с собой из дома. Напиши конкретно, что приготовишь и возьмешь.\n2️⃣ Реши, какой прием пищи или перекус будешь покупать по дороге. Представь, что у тебя есть кафе, заправка или магазин, и выбери конкретный вариант.\n3️⃣ Распредели еду так, чтобы часть калорий оставить на покупку по пути, а не съесть весь запас заранее.\n4️⃣ Проверь весь план под свою калорийность: чтобы в рационе оставалось место для белка, углеводов и жиров.\n5️⃣ Если какой-то вариант не вписывается — измени порцию или выбор, а не отказывайся от поездки и не оставляй питание на случайность.\n\nНапиши одним сообщением: что берешь из дома, что планируешь купить по дороге и как это вписывается в твою калорийность.",
    "Что ты решила взять из дома?\nЧто планируешь купить по дороге?\nУдалось ли оставить место в калорийности для еды вне дома?\nЧто оказалось самым сложным при планировании?"
)

# Day 25 gets concrete, task-focused feedback instead of the generic reflection response.
_original_reflection_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 25:
        t = text.strip().lower()

        has_home = any(p in t for p in ("из дома", "взяла", "взял", "приготов", "контейнер", "сэндвич", "бутер", "йогурт", "творог", "фрукты", "перекус"))
        has_road = any(p in t for p in ("по дороге", "в кафе", "на заправ", "магазин", "куплю", "купить", "ресторан", "столов"))
        has_calories = any(p in t for p in ("ккал", "калори", "калораж", "остат", "впис", "бжу", "белок", "углевод", "жир"))

        if has_home and has_road and has_calories:
            return (
                "🌿 Отлично — ты не пытаешься контролировать всю поездку до мелочей, а заранее создаешь опору.\n\n"
                "Ты разделила питание на две части: то, что удобно взять с собой, и то, что можно спокойно купить по дороге. И главное — оставила место в своей калорийности под реальную ситуацию.\n\n"
                "Именно так работает адаптация: не искать идеальную еду, а заранее иметь несколько рабочих решений."
            )

        if has_home and not has_road:
            return (
                "🌿 Хорошее начало: ты заранее подготовила еду из дома.\n\n"
                "Теперь добавь вторую часть задания — реши, что будешь есть по дороге. Важно не пытаться взять с собой абсолютно всю еду на день. Оставь часть калорийности на покупку в кафе, магазине или на заправке.\n\n"
                "Так ты тренируешь не контроль каждой крошки, а умение адаптировать рацион под обстоятельства."
            )

        if has_road and not has_home:
            return (
                "🌿 Ты уже подумала о еде по дороге — это важная часть навыка.\n\n"
                "Теперь выбери хотя бы один прием пищи или перекус, который удобно взять из дома. Это даст тебе опору в поездке и позволит не зависеть полностью от того, что окажется по пути.\n\n"
                "А оставшиеся калории можно спокойно оставить на еду вне дома."
            )

        return (
            "🌿 Здесь важно не просто придумать меню на день, а потренировать конкретный навык адаптации.\n\n"
            "Сначала выбери, что удобно взять из дома: 1–2 приема пищи или перекуса. Затем реши, что будешь покупать по дороге. После этого проверь весь план под свою калорийность и оставь часть калорий на еду вне дома.\n\n"
            "Напиши конкретные продукты/блюда, а не просто «возьму еду» или «поем в кафе»."
        )

    return _original_reflection_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback

# Keep all previous patches and production startup logic.
runpy.run_module("day24_patch", run_name="__main__")
