import runpy
import content
import bot

# Day 25: поездка — часть еды из дома, часть покупаем по дороге.
content.DAY_TASKS[25] = (
    "Сегодня учимся планировать питание в поездке так, чтобы не зависеть полностью от еды по дороге и при этом не брать с собой весь рацион.",
    "Представь, что завтра ты уезжаешь на весь день. Твоя задача — заранее распределить питание под свою калорийность.\n\nСделай конкретный план:\n1️⃣ Выбери 1–2 приема пищи или перекуса, которые удобно взять с собой из дома. Напиши конкретно, что это будет.\n2️⃣ Выбери 1 прием пищи, который ты поешь по дороге. Представь, что покупаешь его в кафе, магазине или на заправке, и назови конкретный вариант.\n3️⃣ Оставь часть своей калорийности на еду по дороге — не нужно съедать весь дневной запас дома.\n4️⃣ Проверь план: хватает ли тебе белка, есть ли углеводы и жиры, и вписывается ли всё в твою калорийность.\n\nНапиши одним сообщением в формате:\n🏠 Из дома: ...\n🚗 По дороге: ...\n📊 Калорийность: ... ккал, из них на еду по дороге оставляю примерно ... ккал.\n\nЗадача — не составить идеальное меню, а научиться заранее продумывать питание в реальной поездке.",
    "Что ты взяла бы из дома?\nЧто выбрала бы по дороге?\nСколько калорий оставила бы на еду вне дома?\nЧто в таком планировании оказалось самым сложным?"
)

# Day 25: never fall back to the generic reflection template.
_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 25:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()

    has_home = any(p in t for p in (
        "из дома", "взяла с собой", "возьму с собой", "приготовлю", "контейнер",
        "бутерброд", "сэндвич", "творог", "йогурт", "фрукты", "перекус", "ланчбокс"
    ))
    has_road = any(p in t for p in (
        "по дороге", "в кафе", "кафе", "заправк", "магазин", "куплю", "купить",
        "ресторан", "столов", "покуп"
    ))
    has_calories = any(p in t for p in (
        "ккал", "калори", "калораж", "остат", "впис", "бжу", "белок", "углевод", "жир"
    ))

    if has_home and has_road and has_calories:
        return (
            f"🌿 Разбираем твой план\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Здесь есть главное: ты разделила питание на две части — то, что удобно взять из дома, и то, что можно купить по дороге. "
            "При этом ты ориентировалась на свою калорийность и оставила место для еды вне дома.\n\n"
            "Это и есть навык адаптации: не пытаться заранее проконтролировать всю поездку, а иметь опору и несколько рабочих вариантов."
        )

    if has_road and not has_home:
        return (
            f"🌿 Разбираем твой ответ\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Ты уже определилась с едой по дороге. Но сегодня нам важно потренировать именно распределение питания. "
            "Добавь к плану 1–2 продукта или приема пищи, которые удобно взять из дома, а часть калорий оставь на то, что купишь по пути.\n\n"
            "Так у тебя будет и запасной вариант с собой, и свобода выбрать еду в дороге."
        )

    if has_home and not has_road:
        return (
            f"🌿 Разбираем твой ответ\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Еду из дома ты уже продумала. Теперь добавь вторую часть: что конкретно ты будешь есть или покупать по дороге? "
            "Не нужно брать с собой весь рацион на день — оставь часть калорийности для еды вне дома.\n\n"
            "Именно это сегодня тренируем: уметь сочетать подготовленную еду и спонтанный выбор по пути."
        )

    if has_calories:
        return (
            f"🌿 Смотрим на твой план\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Хорошо, что ты связала выбор с калорийностью. Теперь сделай план более конкретным: назови, что именно берешь из дома и что именно будешь покупать по дороге.\n\n"
            "Нам важно не просто знать остаток калорий, а уметь превратить его в реальные решения во время поездки."
        )

    return (
        f"🌿 Разбираем твой ответ\n\n"
        f"Ты написала: «{answer}».\n\n"
        "Чтобы выполнить сегодняшний навык полностью, раздели план на две части:\n"
        "🏠 что конкретно берешь из дома;\n"
        "🚗 что конкретно будешь есть или покупать по дороге;\n"
        "📊 сколько примерно калорий оставляешь на еду вне дома.\n\n"
        "Не ищи идеальные продукты. Нам важно потренировать умение организовать питание так, чтобы поездка не ломала твой обычный рацион."
    )


bot.reflection_feedback = reflection_feedback

# Keep the existing chain and startup logic.
runpy.run_module("day24_patch", run_name="__main__")
