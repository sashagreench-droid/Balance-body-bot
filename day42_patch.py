_original_start_reflection = bot.start_reflection
_original_reflection_feedback = bot.reflection_feedback


async def start_reflection(q, context):
    uid = q.from_user.id
    u = db.user(uid)
    n = u["current_day"] if u else None

    if n == 42:
        context.user_data["awaiting_reflection"] = True
        await q.message.reply_text(
            "🌿 <b>Теперь рефлексия</b>\n\n"
            "1️⃣ В какой ситуации тебе чаще всего хочется использовать еду как способ отдохнуть или переключиться?\n\n"
            "2️⃣ Какой альтернативный способ отдыха из сегодняшнего списка тебе кажется самым реалистичным и почему?\n\n"
            "Напиши ответ одним сообщением. Я дам обратную связь именно по твоему ответу, а потом мы завершим день.",
            parse_mode="HTML",
        )
        return

    await _original_start_reflection(q, context)


def reflection_feedback(day, text, uid=None):
    if day != 42:
        return _original_reflection_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()

    if any(x in t for x in ("после работ", "вечер", "вечером", "устал", "устала", "день законч", "стресс", "напряж")):
        return (
            "❤️ Ты хорошо заметила сам момент, в котором еда становится способом переключиться. "
            "Это уже полезное наблюдение: теперь ты можешь не просто автоматически идти по привычному сценарию, а сначала увидеть, что именно тебе нужно в этот момент.\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Сохрани названный тобой альтернативный вариант и попробуй использовать его именно в этой ситуации. А если после этого поймёшь, что действительно голодна — спокойно поешь. Здесь мы не заменяем еду запретом, а добавляем тебе ещё один способ заботиться о себе."
        )

    if any(x in t for x in ("душ", "ванн", "прогул", "музык", "книг", "сериал", "фильм", "подкаст", "хобби", "общ", "чай", "отдых")):
        return (
            "❤️ Хороший выбор — ты назвала конкретный способ переключиться, а не абстрактное «отдохнуть». "
            "Именно конкретика помогает в реальной ситуации: когда наступает знакомый момент, тебе не нужно заново придумывать, что делать.\n\n"
            f"Твой вариант: «{answer}».\n\n"
            "Теперь важно проверить его в той ситуации, которую ты назвала, и посмотреть, какую потребность он закрывает — расслабление, переключение, удовольствие или паузу."
        )

    return (
        "❤️ В твоём ответе уже есть главное — ты пытаешься отделить желание поесть от желания отдохнуть или переключиться.\n\n"
        f"Ты написала: «{answer}».\n\n"
        "Теперь выбери один конкретный способ отдыха из задания и привяжи его к одной ситуации из своего дня. Так новый вариант будет не просто идеей, а готовым сценарием, которым можно воспользоваться в следующий раз."
    )


bot.start_reflection = start_reflection
bot.reflection_feedback = reflection_feedback
