_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 34:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    movement_words = ("ход", "лестниц", "прогул", "пеш", "вст", "уборк", "магазин", "дорог", "шаг", "движ")
    concrete = sum(1 for w in movement_words if w in t)
    easy = any(w in t for w in ("легко", "легче", "просто", "смогу", "реально", "удобно"))
    barrier = any(w in t for w in ("мешает", "сложно", "трудно", "не хватает", "сид", "времени", "устал"))

    if concrete >= 3 and easy:
        return (
            "🚶 Отлично. Ты не просто написала «больше двигаться», а нашла конкретные точки в своём дне, где движение действительно можно увеличить.\n\n"
            f"Ты выбрала:\n{answer}\n\n"
            "Именно такие решения и формируют устойчивую привычку: они привязаны к уже существующим ситуациям и не требуют каждый день искать дополнительную мотивацию.\n\n"
            "Теперь главное — не пытаться внедрить всё сразу. Выбери одну самую простую точку и начни повторять её регулярно. ❤️"
        )

    if barrier:
        return (
            "🌿 Хорошо, что ты заметила, что именно мешает тебе больше двигаться. Это важнее, чем просто поставить цель «делать больше шагов».\n\n"
            f"Ты написала:\n{answer}\n\n"
            "Попробуй выбрать одно действие, которое обходится без дополнительного времени и не требует особой мотивации. Например, часть дороги пешком, лестница или короткие паузы в течение рабочего дня.\n\n"
            "Цель не в том, чтобы резко увеличить нагрузку, а в том, чтобы найти движение, которое естественно впишется именно в твою жизнь. ❤️"
        )

    return (
        "🚶 Давай сделаем ответ конкретнее.\n\n"
        "Нам нужны 3 реальные точки в твоём дне:\n\n"
        "1️⃣ Сейчас я обычно… → вместо этого могу…\n"
        "2️⃣ Сейчас я обычно… → вместо этого могу…\n"
        "3️⃣ Сейчас я обычно… → вместо этого могу…\n\n"
        "А затем выбери одну, которую тебе будет легче всего начать делать регулярно.\n\n"
        "❤️ Не ищи идеальный вариант — ищи тот, который действительно впишется в твою жизнь."
    )


bot.reflection_feedback = reflection_feedback
