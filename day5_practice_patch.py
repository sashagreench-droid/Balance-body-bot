_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 5:
        t = (text or "").strip().lower()
        parts = []

        if any(x in t for x in ("голод", "голодна", "голодный", "есть хочу", "хочу есть")):
            parts.append("Если перекус появляется на фоне настоящего голода, это не повод считать его ошибкой. Это сигнал, что между приемами пищи тебе может быть действительно нужна еда.")

        if any(x in t for x in ("сладк", "конфет", "шоколад", "печень", "десерт")):
            parts.append("Ты заметила тягу именно к сладкому. Теперь полезно смотреть не только на сам продукт, но и на момент: сколько прошло после еды, насколько ты была голодна и что происходило прямо перед желанием сладкого.")

        if any(x in t for x in ("вечер", "ночь", "после работы", "работ", "устал", "усталость")):
            parts.append("У тебя проявляется связь с временем дня или усталостью. Это уже конкретный сценарий, с которым дальше можно работать: не запрещать вечернюю еду, а заранее понимать, что именно тебе в этот момент нужно.")

        if any(x in t for x in ("скука", "скуч", "стресс", "нерв", "эмоци", "за компанию", "компани", "привыч")):
            parts.append("Похоже, в части эпизодов желание поесть запускается не голодом, а контекстом или состоянием. Это важное наблюдение: сначала мы учимся замечать такой момент, а уже потом выбираем, что с ним делать.")

        if any(x in t for x in ("автомат", "рядом", "увидел", "увидела", "запах", "на автомате")):
            parts.append("Ты заметила автоматический триггер — еда оказалась рядом, попалась на глаза или сработал привычный сценарий. Сам факт, что ты его увидела, уже даёт возможность в следующий раз сделать паузу перед выбором.")

        if any(x in t for x in ("не было", "нет перекус", "не перекусы", "не захотел", "не захотела")):
            parts.append("Если сегодня перекусов почти не было, это тоже результат наблюдения. Важно не создавать их специально, а понять, в какие дни и при каких условиях они появляются.")

        if any(x in t for x in ("понял", "поняла", "узнал", "узнала", "заметил", "заметила", "сценарий")):
            parts.append("Ты уже переводишь наблюдение в конкретный сценарий. Именно такие повторения постепенно позволяют тебе самой понимать своё питание без постоянного внешнего контроля.")

        if parts:
            return "Спасибо за честный разбор ❤️\n\n" + "\n\n".join(parts) + "\n\nНе нужно сейчас запрещать себе перекусы. Забираем наблюдение: что именно запускает желание поесть и насколько это связано с голодом."

        return (
            "Спасибо за честный ответ ❤️\n\n"
            "Сегодня важно было не убрать перекусы, а увидеть их контекст: когда они появляются, насколько ты голодна и что происходит прямо перед ними. "
            "Теперь у тебя есть материал, с которым можно работать дальше."
        )

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
