# Day 26: specific feedback instead of the generic reflection template.
_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 26:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()

    pairs = {
        "салат": any(p in t for p in ("без заправ", "без соус", "с заправ")),
        "кофе": any(p in t for p in ("капучино", "авторск")),
        "мороженое": any(p in t for p in ("пломбир", "с орех")),
        "роллы": any(p in t for p in ("маки", "майонез", "шапоч")),
    }
    answered = sum(pairs.values())
    has_surprise = any(p in t for p in ("удив", "неожидан", "самой неожидан", "больше всего"))

    if answered == 4 and has_surprise:
        return (
            f"🌿 Разбираем твой ответ\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Ты сравнила все четыре пары и посмотрела, что именно добавляет калорийность. Это и есть сегодняшний навык: замечать заправки, добавки и состав, которые могут заметно менять калорийность привычного блюда или напитка.\n\n"
            "Главное — не искать «правильную» или «запрещенную» еду. Ты можешь выбрать любой вариант, но теперь понимаешь, где калорийность может быть выше и можешь учитывать это в своем рационе."
        )

    if answered > 0:
        missing = [name for name, ok in pairs.items() if not ok]
        return (
            f"🌿 Разбираем твой ответ\n\n"
            f"Ты написала: «{answer}».\n\n"
            f"Ты уже сравнила часть вариантов. Осталось разобрать: {', '.join(missing)}.\n\n"
            "Посмотри калорийность обоих вариантов и выбери тот, который оставит больше места в твоем рационе. В конце напиши, какая пара удивила тебя больше всего."
        )

    return (
        f"🌿 Давай сравним конкретно\n\n"
        f"Ты написала: «{answer}».\n\n"
        "Сегодня сравни 4 пары:\n"
        "🥗 салат с заправкой / салат без заправки\n"
        "☕ обычный капучино / авторский кофе\n"
        "🍦 обычный пломбир / мороженое с орехами\n"
        "🍣 роллы с майонезной шапочкой / роллы маки\n\n"
        "Для каждой пары выбери вариант, который обычно будет менее калорийным, и напиши свой выбор. Затем укажи, какая пара удивила тебя больше всего."
    )


bot.reflection_feedback = reflection_feedback

# Keep the existing patch chain and startup logic.
runpy.run_module("day25_patch", run_name="__main__")
