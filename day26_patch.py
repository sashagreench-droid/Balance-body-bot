import runpy
import content
import bot

# Day 26: concrete practice — identify calorie-dense products and learn to account for portions.
content.DAY_TASKS[26] = (
    "Сегодня учимся замечать продукты, которые легко недооценить по калорийности.",
    "Открой холодильник, кухонный шкаф или посмотри на продукты, которые чаще всего добавляешь в еду.\n\nВыбери 3 продукта, которые легко съесть или добавить больше, чем планировала. Например: масло, орехи, сыр, соус, шоколад, арахисовая паста, авокадо или другой продукт из твоего рациона.\n\nДля каждого продукта напиши:\n1️⃣ Что это за продукт?\n2️⃣ Сколько ккал в 100 г?\n3️⃣ Какую порцию ты обычно съедаешь/добавляешь?\n4️⃣ Сколько примерно ккал дает именно твоя порция?\n\nА затем ответь: какой из трех продуктов оказался самым калорийно-плотным и какой проще всего недооценить?\n\nВажно: мы не ищем «плохие» продукты и ничего не запрещаем. Задача — увидеть, где маленькая порция может давать заметное количество калорий, чтобы ты могла учитывать это в своем рационе.",
    "Какой продукт тебя удивил больше всего?\nЕсть ли продукт, который ты раньше добавляла почти автоматически и не учитывала?\nЧто теперь будешь делать иначе: уменьшать порцию, учитывать ее в рационе или просто внимательнее относиться к количеству?"
)

_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 26:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()

    has_products = any(p in t for p in (
        "масл", "орех", "сыр", "соус", "шоколад", "паст", "авокадо", "майонез",
        "сливк", "колбас", "ветчин", "сырок", "семеч", "тахин", "арахис"
    ))
    has_kcal = any(p in t for p in ("ккал", "калори", "ккал/100", "на 100"))
    has_portion = any(p in t for p in ("г", "гр", "ложк", "порци", "кусоч", "мл"))

    if has_products and has_kcal and has_portion:
        return (
            f"🌿 Разбираем твой ответ\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Сегодня ты не просто назвала калорийные продукты — ты посмотрела на их калорийность и связала ее со своей обычной порцией. Именно это помогает замечать «незаметные» калории без запретов.\n\n"
            "Главный вывод: калорийно-плотный продукт не нужно исключать. Важно понимать, сколько его реально попадает в рацион и учитывать это количество.\n\n"
            "Так ты управляешь порцией осознанно, а не узнаешь о калорийности продукта только после того, как он уже оказался в дневном рационе."
        )

    if has_products and not has_kcal:
        return (
            f"🌿 Почти готово\n\n"
            f"Ты выбрала продукты: «{answer}».\n\n"
            "Теперь добавь к каждому калорийность на 100 г и свою обычную порцию. Например: «орехи — 600 ккал/100 г, обычно ем 20 г — это около 120 ккал».\n\n"
            "Нам важно увидеть не только название продукта, а понять, сколько калорий реально дает твоя порция."
        )

    if has_kcal and not has_products:
        return (
            f"🌿 Давай сделаем ответ конкретнее\n\n"
            f"Ты написала: «{answer}».\n\n"
            "Теперь выбери 3 конкретных продукта из дома — например масло, орехи и сыр — и для каждого укажи: ккал на 100 г + сколько ты обычно съедаешь.\n\n"
            "Задача сегодня не в том, чтобы просто знать цифры, а в том, чтобы увидеть, какие продукты дают много калорий даже в небольшой порции."
        )

    return (
        f"🌿 Давай выполним задание полностью\n\n"
        f"Ты написала: «{answer}».\n\n"
        "Выбери 3 продукта дома, которые легко недооценить по калорийности. Для каждого напиши:\n"
        "🥜 продукт\n"
        "📊 ккал на 100 г\n"
        "⚖️ твоя обычная порция\n"
        "🔥 сколько ккал получается в этой порции\n\n"
        "В конце напиши, какой продукт оказался самым неожиданным. Продукты не запрещаем — учимся видеть их реальную калорийность и количество."
    )


bot.reflection_feedback = reflection_feedback

# Keep the existing patch chain and startup logic.
runpy.run_module("day25_patch", run_name="__main__")
