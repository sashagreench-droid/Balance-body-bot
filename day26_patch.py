content.DAY_TASKS[26] = (
    "Сегодня учимся замечать, как заправки, добавки и состав меняют калорийность привычной еды.",
    "Сравни 4 пары и выбери в каждой вариант, который обычно будет менее калорийным:\n\n"
    "1️⃣ 🥗 Салат с заправкой или салат без заправки\n"
    "2️⃣ ☕ Обычный капучино или авторский кофе\n"
    "3️⃣ 🍦 Обычный пломбир или мороженое с орехами\n"
    "4️⃣ 🍣 Роллы с майонезной шапочкой или роллы маки\n\n"
    "Твоя задача — не просто угадать. Посмотри калорийность вариантов в меню или приложении и сравни их.\n\n"
    "Ответь одним сообщением:\n"
    "🥗 Салат — выбираю ...\n"
    "☕ Кофе — выбираю ...\n"
    "🍦 Мороженое — выбираю ...\n"
    "🍣 Роллы — выбираю ...\n\n"
    "И напиши: какая пара удивила тебя больше всего?\n\n"
    "Задача — увидеть, что дополнительные калории часто появляются за счет заправок, добавок и состава, а не потому, что продукт сам по себе «плохой».",
    "Какие варианты ты выбрала?\nКакая пара оказалась самой неожиданной?\nЧто теперь будешь замечать при выборе похожих продуктов?"
)

# Day 26: specific feedback that reacts to the actual answer instead of using a generic reflection template.
_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 26:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()

    if any(p in t for p in ("кофе", "капучино", "авторск")):
        return (
            "☕ Хороший пример — кофе как раз легко недооценить.\n\n"
            "Важен не сам факт, что это кофе, а его состав: молоко, сиропы, сливки, шоколад и другие добавки могут заметно менять калорийность напитка. "
            "Поэтому два напитка на основе кофе могут сильно отличаться по калорийности.\n\n"
            "Сегодняшний навык — не запрещать себе авторский кофе, а замечать, из чего он состоит и учитывать это при выборе. ❤️"
        )

    if any(p in t for p in ("салат", "заправ")):
        return (
            "🥗 Да, салат — отличный пример калорийной ловушки.\n\n"
            "Сам салат может быть довольно легким, но заправка способна заметно изменить его калорийность. Поэтому при выборе блюда важно смотреть не только на основу, но и на то, что к ней добавлено.\n\n"
            "Не нужно отказываться от заправки. Важно просто видеть её как часть блюда и учитывать при выборе. ❤️"
        )

    if any(p in t for p in ("морож", "пломбир", "орех")):
        return (
            "🍦 Здесь тоже легко ориентироваться только на название продукта.\n\n"
            "Обычный пломбир и мороженое с орехами могут выглядеть как одинаковый десерт, но добавки меняют его состав и калорийность. Орехи сами по себе не «плохие» — просто они добавляют блюду энергии, и это стоит учитывать.\n\n"
            "Вот что мы сегодня тренируем: замечать не только сам продукт, но и его добавки. ❤️"
        )

    if any(p in t for p in ("ролл", "маки", "майонез", "шапоч")):
        return (
            "🍣 Роллы — хороший пример того, как добавка меняет привычное блюдо.\n\n"
            "Майонезная шапочка — это уже дополнительный ингредиент, поэтому при сравнении роллов стоит смотреть не только на начинку, но и на всё, что добавлено сверху.\n\n"
            "Не нужно делить роллы на «можно» и «нельзя». Ты просто учишься видеть разницу между вариантами и выбирать осознанно. ❤️"
        )

    if any(p in t for p in ("масл", "соус", "напит", "сироп", "сливк")):
        return (
            "🎯 Вот именно такие продукты и добавки мы сегодня учимся замечать.\n\n"
            "Они могут казаться небольшой деталью, но входят в состав блюда или напитка и поэтому тоже влияют на его калорийность.\n\n"
            "Главное — не исключать их автоматически, а учитывать их при выборе. Так ты получаешь больше контроля без лишних запретов. ❤️"
        )

    if any(p in t for p in ("удив", "неожидан", "калори", "калорий")):
        return (
            "🌿 Вот это и было целью сегодняшнего задания.\n\n"
            "Мы смотрим не только на привычное название продукта, но и на состав: заправки, добавки, соусы и напитки могут заметно менять итоговую калорийность.\n\n"
            "Теперь у тебя есть ещё один ориентир для выбора: смотреть, что именно добавлено к блюду, а не оценивать его только по названию. ❤️"
        )

    return (
        "🌿 Хорошее наблюдение.\n\n"
        "Сегодня важно было увидеть, что калорийность привычного блюда или напитка зависит не только от его основы. Заправка, соус, сироп, орехи, сливки или другая добавка тоже становятся частью итогового блюда.\n\n"
        "Поэтому задача не в том, чтобы запомнить список «правильных» продуктов. Твоя задача — научиться замечать состав и понимать, где есть дополнительные калории. ❤️"
    )


bot.reflection_feedback = reflection_feedback

# Keep the existing patch chain and startup logic.
runpy.run_module("day25_patch", run_name="__main__")
