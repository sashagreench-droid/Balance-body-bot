_original_start_reflection = bot.start_reflection
_original_reflection_feedback = bot.reflection_feedback


async def start_reflection(q, context):
    uid = q.from_user.id
    u = db.user(uid)
    n = u["current_day"] if u else None

    if n == 41:
        context.user_data["awaiting_reflection"] = True
        await q.message.reply_text(
            "🌿 <b>Теперь рефлексия</b>\n\n"
            "1️⃣ Какой источник клетчатки из твоего списка тебе проще всего добавить в обычный день?\n\n"
            "2️⃣ В какой прием пищи тебе будет легче всего это сделать?\n\n"
            "Напиши ответ одним сообщением. Я дам обратную связь именно по твоему ответу, а потом мы завершим день.",
            parse_mode="HTML",
        )
        return

    await _original_start_reflection(q, context)


def reflection_feedback(day, text, uid=None):
    if day != 41:
        return _original_reflection_feedback(day, text, uid)

    t = text.lower()
    if any(x in t for x in ("овся", "каша", "греч", "хлеб", "круп")):
        return (
            "❤️ Хороший вариант: ты выбрала источник клетчатки, который легко встроить в привычный прием пищи. "
            "Такой подход и нужен — не создавать отдельное сложное правило, а добавлять подходящий продукт туда, где еда уже есть."
        )
    if any(x in t for x in ("овощ", "брокк", "капуст", "морков", "огур", "помид", "перец")):
        return (
            "❤️ Отлично, ты выбрала овощи как реальный способ добавить клетчатку в обычный рацион. "
            "Особенно ценно, что это можно делать без отдельного приготовления: добавить овощи к уже привычному обеду или ужину и постепенно сделать это своей нормой."
        )
    if any(x in t for x in ("яблок", "груш", "апельс", "ягод", "фрукт")):
        return (
            "❤️ Хороший выбор: фрукты легко встроить в уже существующий рацион, поэтому тебе не нужно придумывать отдельный сложный сценарий. "
            "Сохрани именно тот вариант и прием пищи, который назвала, — так привычка будет проще закрепляться."
        )
    if any(x in t for x in ("фасол", "чечев", "нут", "горох", "бобов")):
        return (
            "❤️ Ты выбрала хороший вариант, но главное здесь — сделать его удобным именно для тебя. "
            "Если заранее знать, с каким блюдом ты будешь использовать этот продукт, добавлять его в рацион становится намного проще."
        )
    if any(x in t for x in ("орех", "семен", "чиа", "льн", "тыквен")):
        return (
            "❤️ Удобный выбор: такие продукты легко держать под рукой и добавлять небольшими порциями в привычные блюда. "
            "Это как раз пример того, как знание нескольких простых источников помогает собирать рацион без лишних усложнений."
        )
    return (
        "❤️ Ты уже выбрала конкретный источник клетчатки и подумала, куда его встроить. "
        "Теперь главное — не превращать это в обязательное правило: выбери один удобный вариант и попробуй сделать его частью своего обычного приема пищи."
    )


bot.start_reflection = start_reflection
bot.reflection_feedback = reflection_feedback
