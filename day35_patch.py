_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 35:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    concrete = any(w in t for w in ("шаг", "прогул", "пеш", "останов", "телефон", "магазин", "дорог"))
    realistic = any(w in t for w in ("реалист", "комфорт", "удоб", "смогу", "без давления", "без фанатизма"))
    pressure = any(w in t for w in ("давлен", "гонк", "обязатель", "добивать", "фанатизм", "надо любой ценой"))

    if concrete and realistic:
        return (
            "👟 Отлично. Ты посмотрела на шаги не как на обязательную цифру, а как на ориентир для своей реальной активности.\n\n"
            f"Ты написала:\n{answer}\n\n"
            "Особенно хорошо, что ты опираешься на свой обычный уровень и выбрала конкретные способы добавить движение. Такой подход гораздо устойчивее, чем резко ставить себе большую цель.\n\n"
            "Теперь главное — использовать диапазон как ориентир, а не как экзамен. Если в какой-то день шагов меньше, это не отменяет твою систему. ❤️"
        )

    if pressure:
        return (
            "🌿 Важное наблюдение: ты уже заметила риск превратить шаги в обязательную гонку за цифрой.\n\n"
            f"Ты написала:\n{answer}\n\n"
            "Попробуй оставить шаги именно ориентиром. Нам не нужна ситуация, когда вечером приходится специально ходить только ради того, чтобы увидеть нужную цифру.\n\n"
            "Выбери небольшой способ добавить движение в обычный день и оценивай его по тому, насколько легко тебе повторять его регулярно. ❤️"
        )

    return (
        "👟 Давай сделаем ответ конкретнее.\n\n"
        "Напиши 3 вещи:\n\n"
        "1️⃣ сколько шагов у тебя обычно бывает;\n"
        "2️⃣ какой диапазон для тебя реалистичен;\n"
        "3️⃣ какие 2–3 простых действия помогут немного больше двигаться.\n\n"
        "🌿 Помни: шаги — это ориентир, а не обязательная цифра, которую нужно любой ценой выполнить."
    )


bot.reflection_feedback = reflection_feedback
