_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 32:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    situations = sum(1 for w in ("ресторан", "поезд", "встреч", "мероприят") if w in t)
    rule_markers = sum(1 for w in ("правило", "буду", "выбираю", "ориентир", "сначала", "если") if w in t)
    has_difficulty = any(w in t for w in ("сложно", "трудно", "сложнее", "сомнева", "боюсь", "страшно", "не знаю"))
    has_reason = any(w in t for w in ("потому что", "мне подходит", "мне удобно", "мне важно", "так проще", "чтобы"))

    if situations >= 2 and rule_markers >= 3 and has_reason:
        return (
            "🍽️ Отлично — ты уже переводишь адаптацию из абстрактной идеи в конкретные решения.\n\n"
            f"Твоя стратегия:\n{answer}\n\n"
            "Особенно важно, что ты сформулировала именно свои правила и объяснила, зачем они тебе. Такое правило работает как ориентир в момент выбора, а не как очередной запрет.\n\n"
            "Теперь обрати внимание на ту ситуацию, которую ты назвала самой сложной. Именно там твоя стратегия должна быть максимально простой: одно понятное действие, которое ты сможешь выполнить даже без идеальных условий.\n\n"
            "❤️ Сохрани свои 3 правила. Дальше мы будем учиться применять их автоматически, а не каждый раз начинать с нуля."
        )

    if has_difficulty:
        return (
            "🌿 Хорошо, что ты заметила, какая ситуация вызывает больше всего сложностей. Это не значит, что ты не умеешь адаптироваться — наоборот, мы нашли конкретное место для тренировки.\n\n"
            f"Ты написала:\n{answer}\n\n"
            "Попробуй превратить сложность в одно простое действие. Не «питаться идеально», а решить, что именно ты сделаешь: как выберешь блюдо, на что посмотришь в меню или как поступишь, если доступен только ограниченный выбор.\n\n"
            "Дополни три правила и отдельно напиши свой следующий шаг для самой сложной ситуации. ❤️"
        )

    return (
        "🍽️ Давай сделаем стратегию конкретнее.\n\n"
        "Нам нужны 3 правила, которыми ты реально сможешь пользоваться вне дома:\n\n"
        "🍴 В ресторане я…\n"
        "🚗 В поездке я…\n"
        "🥂 На встречах / мероприятиях я…\n\n"
        "Для каждого добавь: «почему это правило подходит мне».\n\n"
        "И выбери одну самую сложную ситуацию. Напиши, что конкретно ты сделаешь в следующий раз.\n\n"
        "🌿 Важно: это не список запретов. Твои правила должны помогать адаптировать питание к жизни, а не ограничивать ее. ❤️"
    )


bot.reflection_feedback = reflection_feedback
