_previous_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day != 31:
        return _previous_feedback(day, text, uid)

    answer = text.strip()
    t = answer.lower()
    food_words = (
        "яйц", "омлет", "куриц", "индейк", "рыб", "лосос", "тунц", "творог",
        "йогурт", "сыр", "морепродукт", "кревет", "мяс", "говядин", "свин",
        "бобов", "чечев", "фасол", "рис", "греч", "овсян", "каша", "хлеб",
        "тост", "макарон", "картоф", "лаваш", "фрукт", "яблок", "банан",
        "ягод", "овощ", "салат", "авокадо", "орех", "гранол", "соус", "шоколад",
        "десерт", "сырник", "блин"
    )
    found = [w for w in food_words if w in t]
    has_situations = sum(1 for w in ("завтрак", "обед", "ужин", "быстро", "сладк", "нет времени") if w in t)
    has_list = sum(1 for i in range(1, 6) if str(i) in t) >= 5
    has_repeat = any(w in t for w in ("повтор", "регуляр", "часто", "буду есть", "готова есть", "люблю"))

    if len(set(found)) >= 4 and has_list:
        return (
            "🍽️ Отлично — у тебя уже появляется не просто список продуктов, а собственная библиотека рабочих сочетаний.\n\n"
            f"Ты написала:\n{answer}\n\n"
            "Самое ценное здесь — ты соединяешь продукты, которые тебе нравятся, а не пытаешься каждый раз придумать «идеальное» блюдо. Именно так питание становится повторяемым и удобным.\n\n"
            "Теперь выдели 2 сочетания, которые действительно готовы выручать тебя в обычной жизни. Одно может быть максимально быстрым, второе — тем, которое закрывает желание сладкого. Чем больше таких опор у тебя будет, тем меньше решений придется принимать с нуля. ❤️"
        )

    if has_repeat or has_situations >= 2:
        return (
            "🍽️ Хорошо, что ты уже привязываешь еду к реальным ситуациям, а не только к рецептам.\n\n"
            f"Твой ответ:\n{answer}\n\n"
            "Рабочее сочетание — это то, которое хочется есть, легко собрать и реально повторить. Поэтому особенно обрати внимание на варианты, которые могут выручить тебя в загруженный день или когда хочется сладкого.\n\n"
            "Допиши до 5 конкретных сочетаний и выбери 2 самых универсальных. Для каждого напиши, в какой ситуации ты будешь к нему возвращаться. ❤️"
        )

    return (
        "🍽️ Давай сделаем список более конкретным.\n\n"
        "Нам нужны не названия вроде «полезный завтрак», а реальные сочетания продуктов. Например:\n\n"
        "🍳 Омлет + хлеб + овощи\n"
        "🍚 Рис + курица + овощи\n"
        "🥣 Йогурт + ягоды + гранола\n"
        "🌯 Лаваш + индейка + овощи\n"
        "🍫 Твой вариант на случай, когда хочется сладкого\n\n"
        "📋 Напиши минимум 5 своих сочетаний и отметь:\n"
        "1️⃣ какое ты будешь повторять регулярно;\n"
        "2️⃣ какое выручит, когда нет времени или хочется сладкого.\n\n"
        "Цель — собрать свою личную библиотеку еды, а не найти идеальные рецепты. ❤️"
    )


bot.reflection_feedback = reflection_feedback
