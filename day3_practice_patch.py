# Day 3 feedback should use the actual observation rather than a universal reply.
_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 3:
        t = (text or "").strip().lower()
        answers = bot.db.get_day_answers(uid, 3) if uid is not None else []
        observations = []
        for row in answers:
            kind = row["kind"]
            value = row["value"]
            if kind == "hunger_before":
                observations.append(("голод", value))
            elif kind == "satiety_after":
                observations.append(("сытость", value))

        lines = []
        if observations:
            hunger_values = [int(v) for k, v in observations if k == "голод"]
            satiety_values = [int(v) for k, v in observations if k == "сытость"]
            if hunger_values and satiety_values:
                lines.append(
                    f"Ты уже сравнила {min(len(hunger_values), len(satiety_values))} приём(а/ов) пищи по голоду до и сытости после."
                )
                lines.append(
                    "Это и есть смысл сегодняшнего задания: не угадать граммы, а увидеть, какая привычная порция даёт тебе достаточную сытость."
                )

        if any(p in t for p in ("хватило", "достаточно", "сыт", "насыт")):
            lines.append("Ты заметила, где обычной порции тебе хватило. Это полезная личная ориентировка — её можно использовать без постоянного взвешивания еды.")
        if any(p in t for p in ("хотелось ещё", "хотелось еще", "добав", "не хват", "голодн")):
            lines.append("Ты заметила приём пищи, после которого хотелось ещё. Здесь не нужно автоматически урезать или запрещать еду — сначала важно понять, был ли это физический голод или другой импульс.")
        if any(p in t for p in ("слишком много", "переел", "переполн", "тяжело")):
            lines.append("Ты заметила момент, когда порции оказалось много. Это не ошибка и не повод компенсировать еду — это информация о том, как ты чувствуешь насыщение.")
        if any(p in t for p in ("вкус", "привыч", "эмоци", "компан", "скук", "стресс")):
            lines.append("Ты связала желание продолжить есть не только с физическим голодом. Это важное различие: теперь можно отдельно замечать тело и привычный сценарий.")
        if any(p in t for p in ("удив", "раньше", "не замеч", "понял", "поняла")):
            lines.append("Само это наблюдение уже полезно: ты начинаешь видеть свой реальный объём еды и ощущения после него, а не ориентироваться на абстрактную «правильную порцию».")

        if lines:
            return "Спасибо за честный разбор ❤️\n\n" + "\n\n".join(lines) + "\n\nСегодня ничего не нужно исправлять. Забираем наблюдение как свою личную точку отсчёта и идём дальше."

        return (
            "Спасибо за честный ответ ❤️\n\n"
            "Смысл третьего дня не в том, чтобы определить идеальный размер порции. "
            "Ты учишься замечать: сколько обычно ешь, насколько голодна до еды и насколько сыта после. "
            "Со временем это даст тебе собственный ориентир без постоянного взвешивания."
        )

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
