_original_start_reflection = bot.start_reflection
_original_reflection_feedback = bot.reflection_feedback


async def start_reflection(q, context):
    uid = q.from_user.id
    u = db.user(uid)
    n = u["current_day"] if u else None

    if n == 40:
        context.user_data["awaiting_reflection"] = True
        await q.message.reply_text(
            "🌿 <b>Теперь рефлексия</b>\n\n"
            "1️⃣ Какое из своих достижений тебе было сложнее всего признать?\n\n"
            "2️⃣ Что ты хочешь продолжать делать после курса, чтобы это достижение не осталось только результатом 49 дней?\n\n"
            "Напиши ответ одним сообщением. Я дам обратную связь именно по твоему ответу, а потом мы завершим день.",
            parse_mode="HTML",
        )
        return

    await _original_start_reflection(q, context)


def reflection_feedback(day, text, uid=None):
    if day != 40:
        return _original_reflection_feedback(day, text, uid)

    t = text.lower()
    if any(x in t for x in ("пит", "еда", "рацион", "калор", "бжу", "белок", "слад")):
        return (
            "❤️ И это действительно достижение. Ты говоришь не просто о знании правил, а о том, что стала спокойнее принимать решения в питании. "
            "Именно такой навык важно сохранить: не стремиться к идеальному рациону, а уметь возвращаться к своим обычным решениям без чувства вины."
        )
    if any(x in t for x in ("трен", "движ", "шаг", "спорт", "заряд", "актив")):
        return (
            "❤️ Ты заметила прогресс в движении — и здесь особенно важно, что активность постепенно становится частью обычной жизни. "
            "Сохрани тот формат, который реально вписывается в твой день: регулярность здесь важнее попытки каждый раз сделать максимум."
        )
    if any(x in t for x in ("себ", "увер", "спокой", "критик", "отнош", "люб", "цен")):
        return (
            "❤️ Мне особенно нравится, что ты отметила отношение к себе. Это не мелочь: когда вместо постоянной критики появляется спокойное отношение к своим решениям, поддерживать привычки становится намного легче. "
            "Постарайся сохранить именно эту опору после курса."
        )
    if any(x in t for x in ("план", "режим", "привыч", "регуляр", "систем", "самостоят")):
        return (
            "❤️ Ты заметила не отдельный результат, а изменение в своих привычках и самостоятельности. Это один из самых ценных итогов курса: тебе всё меньше нужен внешний контроль, потому что ты уже умеешь принимать решения сама. "
            "Сохрани тот конкретный сценарий, который назвала, и сделай его частью обычной недели."
        )
    return (
        "❤️ В твоём ответе важно именно то, что ты смогла назвать своё достижение и подумать, как сохранить его дальше. "
        "Не обесценивай это словами «могла бы лучше»: сегодня мы учимся замечать уже сделанное. Выбери одно конкретное действие из своего ответа и продолжай его в обычной жизни."
    )


bot.start_reflection = start_reflection
bot.reflection_feedback = reflection_feedback
