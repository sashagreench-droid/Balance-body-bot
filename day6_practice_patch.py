import bot

# BALANCE BODY — День 6: turn vague pattern spotting into a concrete
# self-observation exercise with triggers, sequence, and a small experiment.

bot.DAYS[5] = (
    6,
    "МОИ ПРИВЫЧНЫЕ СЦЕНАРИИ",
    "НАБЛЮДАЮ",
    "Вижу повторяющиеся пищевые сценарии",
    50,
)

bot.DAY_TASKS[6] = (
    "Сегодня ищем не отдельные перекусы, а повторяющиеся цепочки: что происходит → что я чувствую → что делаю с едой.",
    """Посмотри на свои записи за последние дни и найди минимум 2 повторяющихся пищевых сценария.

Сценарий — это ситуация, которая снова и снова приводит тебя к похожему действию с едой.

Например:
🍫 «После работы я устаю и почти всегда ем сладкое».
☕ «Когда начинаю работать за компьютером, постоянно делаю кофе и беру что-нибудь к нему».
📺 «Вечером включаю сериал и автоматически начинаю что-то есть».
😣 «Когда нервничаю, хочется чего-нибудь вкусного, даже если недавно ела».
🏠 «Придя домой, сразу иду на кухню, потому что это стало привычным ритуалом».

Для каждого из 2 сценариев запиши 5 пунктов:

1. КОГДА это обычно происходит?
Время, день недели или конкретная ситуация.

2. ГДЕ это происходит?
Дома, на работе, в машине, перед телевизором и т.д.

3. ЧТО ПРОИСХОДИТ ПЕРЕД ЕДОЙ?
Работа, усталость, стресс, скука, разговор, сериал, приготовление еды и т.д.

4. ЧТО Я ОБЫЧНО ДЕЛАЮ?
Что именно ем/пью и в каком количестве примерно.

5. ЧТО Я ПОЛУЧАЮ ОТ ЭТОГО?
Сытость, удовольствие, паузу, успокоение, переключение, компанию, ощущение награды или что-то другое.

А теперь выбери ОДИН самый частый сценарий и ответь:
👉 Что в нём запускает меня сильнее всего?
👉 Это больше про физический голод или про привычку/ситуацию/эмоции?
👉 Что я могла бы попробовать сделать иначе в следующий раз — НЕ запрещая себе еду?

Например: если после работы хочется сладкого, можно сначала сделать 10 минут паузы, выпить воды или чая, переодеться и отдохнуть, а затем снова оценить голод. Если голод остался — нормально поесть.

Сегодня не нужно убирать перекусы или заставлять себя «держаться». Нам важно увидеть механизм, который повторяется.""",
    """После задания напиши одним сообщением:

1️⃣ Сценарий №1 — когда/где/что происходит → что я обычно делаю → что получаю.
2️⃣ Сценарий №2 — когда/где/что происходит → что я обычно делаю → что получаю.
3️⃣ Самый частый сценарий — ______.
4️⃣ В следующий раз я попробую ______.

Можно писать коротко, главное — конкретно.""",
)

_original_feedback = bot.reflection_feedback


def reflection_feedback(day, text, uid=None):
    if day == 6:
        t = (text or "").strip().lower()
        if not t:
            return "Напиши хотя бы один конкретный сценарий: когда он происходит, что было перед едой, что ты обычно ешь и что получаешь от этого. Так мы сможем найти закономерность."

        lines = []
        if any(p in t for p in ("вечер", "после работы", "после труд", "дома", "сериал", "телевиз")):
            lines.append("Похоже, у тебя есть привязка еды к определённому вечернему контексту. Здесь полезно разделить два момента: действительно ли ты голодна и что именно запускает желание есть — усталость, отдых, сериал или сам привычный ритуал.")
        if any(p in t for p in ("сладк", "шоколад", "конфет", "десерт")):
            lines.append("Ты заметила конкретный продукт, который появляется в сценарии. Это не значит, что его нужно запрещать. Гораздо полезнее понять, в какой ситуации он становится привычной наградой или способом переключиться.")
        if any(p in t for p in ("стресс", "нерв", "тревог", "злост", "эмоци", "устал", "скуч")):
            lines.append("Здесь важно не бороться с эмоцией через запрет еды. Попробуй сначала заметить состояние и дать себе короткую паузу, а потом решить, нужна ли тебе еда или сейчас нужен другой способ восстановиться.")
        if any(p in t for p in ("кофе", "работ", "компьютер", "за компьютером")):
            lines.append("Ты нашла связь еды с рабочим ритуалом. Попробуй в следующий раз изменить не еду, а саму последовательность: например, сделать паузу без еды и проверить голод через несколько минут.")
        if any(p in t for p in ("голод", "голодна", "голодный", "сыта", "не голод")):
            lines.append("Хорошо, что ты связала сценарий с уровнем голода. Именно это помогает отличать потребность в еде от автоматического действия — без необходимости запрещать себе перекусы.")

        if any(p in t for p in ("привыч", "автомат", "ритуал", "за компанию", "компани")):
            lines.append("Ты увидела повторяющуюся последовательность. Когда сценарий становится заметным, появляется выбор: продолжить его как обычно или попробовать изменить один элемент.")

        if any(p in t for p in ("попроб", "сделаю", "сделать иначе", "в следующий раз", "вместо", "пауза", "прогул", "чай", "вода")):
            lines.append("Отлично: экспериментируем с одним маленьким изменением, а не пытаемся сразу убрать весь сценарий. Так ты проверишь на практике, что действительно тебе помогает.")

        if lines:
            return "Спасибо за конкретный разбор ❤️\n\n" + "\n\n".join(lines) + "\n\nГлавное сегодня — не запретить себе есть, а увидеть цепочку: ситуация → состояние → действие → результат."

        return (
            "Ты начала замечать повторяющиеся сценарии ❤️\n\n"
            "Теперь попробуй найти в своём ответе одну цепочку: что происходит перед едой → что ты чувствуешь → что делаешь → что получаешь. "
            "И выбери один маленький элемент, который можно попробовать изменить в следующий раз без запретов."
        )

    return _original_feedback(day, text, uid)


bot.reflection_feedback = reflection_feedback
